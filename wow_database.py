"""Server-only SQLite/PostgreSQL storage for WOW's existing SQL queries."""
import os
import re
import sqlite3
from contextlib import contextmanager


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class Result:
    def __init__(self, cursor, inserted=False):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.lastrowid = None
        if inserted:
            row = cursor.fetchone()
            self.lastrowid = row['id'] if row else None
    def fetchone(self):
        return self.cursor.fetchone()
    def fetchall(self):
        return self.cursor.fetchall()


class Postgres:
    def __init__(self, raw):
        self.raw = raw
    def execute(self, sql, params=()):
        import psycopg
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            # Every connection already holds the transaction advisory lock.
            return Result(self.raw.execute('SELECT 1'))
        sql = re.sub(r'\bid INTEGER PRIMARY KEY\b', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
        ignored = bool(re.match(r'INSERT OR IGNORE\b', sql, re.I))
        sql = re.sub(r'INSERT OR IGNORE\b', 'INSERT', sql, flags=re.I)
        sql = sql.replace("strftime('%s','now','start of day')", "EXTRACT(EPOCH FROM date_trunc('day', CURRENT_TIMESTAMP AT TIME ZONE 'UTC'))")
        # All SQL is application-owned; literal percent signs need escaping for psycopg.
        sql = sql.replace('%', '%%').replace('?', '%s')
        if ignored:
            sql = sql.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
        # Only tables whose primary key is named id use generated identities.
        match = re.match(r'\s*INSERT INTO (\w+)', sql, re.I)
        inserted = bool(match and match[1].lower() in ID_TABLES)
        if inserted:
            sql = sql.rstrip().rstrip(';') + ' RETURNING id'
        try:
            # A caught duplicate must not leave the outer transaction aborted.
            with self.raw.transaction():
                cursor = self.raw.execute(sql, params)
                return Result(cursor, inserted)
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('Database constraint failed') from error
        except psycopg.ProgrammingError as error:
            raise sqlite3.OperationalError('Database query failed') from error
    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)
    def executemany(self, sql, rows):
        for row in rows:
            self.execute(sql, row)


ID_TABLES = frozenset(('users', 'ai_generations', 'credit_events', 'listings',
    'posts', 'services', 'requests', 'referrals', 'reward_claims', 'jobs',
    'job_applications', 'job_reports', 'nina_products', 'digital_products',
    'motivation_quotes', 'marketing_drafts'))


@contextmanager
def connect(sqlite_path):
    url = os.getenv('DATABASE_URL', '').strip()
    if not url:
        raw = sqlite3.connect(sqlite_path, timeout=20)
        raw.row_factory = sqlite3.Row
        try:
            raw.execute('PRAGMA foreign_keys=ON')
            raw.execute('PRAGMA journal_mode=WAL')
            with raw:
                yield raw
        finally:
            raw.close()
        return
    if not url.startswith(('postgresql://', 'postgres://')):
        raise RuntimeError('DATABASE_URL must be a PostgreSQL connection URI')
    if '[YOUR-PASSWORD]' in url:
        raise RuntimeError('Replace the database password placeholder in Render')
    import psycopg
    # Password may be separate to avoid URL escaping on a phone.
    options = {'password': os.environ['DATABASE_PASSWORD']} if os.getenv('DATABASE_PASSWORD') else {}
    try:
        raw = psycopg.connect(url, sslmode='require', connect_timeout=15,
            prepare_threshold=None, row_factory=row_factory, **options)
    except psycopg.Error:
        # Do not put a credential-bearing DSN into public errors or logs.
        raise RuntimeError('PostgreSQL connection failed. Check Render database settings.') from None
    with raw:
        # Maintain SQLite's serialized transaction semantics, including reward reservations.
        raw.execute('SELECT pg_advisory_xact_lock(1869575971)')
        raw.execute('CREATE SCHEMA IF NOT EXISTS wow_app')
        raw.execute('REVOKE ALL ON SCHEMA wow_app FROM PUBLIC')
        raw.execute('SET LOCAL search_path TO wow_app')
        yield Postgres(raw)
